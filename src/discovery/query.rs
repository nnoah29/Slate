/// Met en minuscules et retire les accents français courants.
fn fold(text: &str) -> String {
    text.chars()
        .flat_map(char::to_lowercase)
        .map(|c| match c {
            'é' | 'è' | 'ê' | 'ë' => 'e',
            'à' | 'â' | 'ä' => 'a',
            'î' | 'ï' => 'i',
            'ô' | 'ö' => 'o',
            'ù' | 'û' | 'ü' => 'u',
            'ç' => 'c',
            other => other,
        })
        .collect()
}

/// Vrai si chaque mot de la requête figure dans le libellé, sans tenir compte de la casse ni des accents.
pub fn matches_query(label: &str, query: &str) -> bool {
    let label = fold(label);
    fold(query)
        .split_whitespace()
        .all(|word| label.contains(word))
}
